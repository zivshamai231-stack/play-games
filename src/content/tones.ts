import type { Lines, Surprise } from "./types";

/* The evening's tone: three full sets of copy for the announcer, the tasks, the punishments, the surprises and the wheel.
   The host can switch tone live. A party's content can add its own private jokes on top (EventContent.copy).
   Placeholders filled in when the game runs: {star} the star's name, {cur} the currency ("תמרים"), {coin} one coin ("תמר"),
   {kingT} the king's title ("מלך התמרים"), {lastT} the last place's title ("התמר היבש").
   Runtime placeholders ({n}, {t}, {r}, {w}, {l}, {game}, {k}, {o}, {c}, {king}, {last}, {start}) are filled by the engine. */

export type ToneId = "calm" | "playful" | "spicy";

export type WheelWho = "last" | "king" | "second" | "losers" | "star" | "everyone" | "below" | "last2" | "none";

export interface TonePack {
  id: ToneId;
  /** what the host sees */
  name: string;
  blurb: string;
  lines: Lines;
  tasks: string[];
  lateTasks: string[];
  bigTask: string | null;
  everyoneTask: string;
  brokeTasks: string[];
  punishments: string[];
  surprises: Surprise[];
  drinkWheel: [label: string, who: WheelWho][];
  lateWheel: [label: string, who: "last" | "king"] | null;
  /** what the announcer says for each soundboard button (by sound id) */
  soundLines: Record<string, string>;
  /** the announcer's voice direction (OpenAI TTS instructions) */
  voice: string;
}

